// ─── POPULATE FUNCTION ───────────────────────────────────────────────────────

async function populatePack(packName, items) {
  const pack = game.packs.get(`dreadlight.${packName}`);
  if (!pack) {
    ui.notifications.error(`Pack dreadlight.${packName} not found!`);
    return;
  }

  // Unlock the pack for editing
  await pack.configure({ locked: false });

  // Clear existing items
  const existing = await pack.getDocuments();
  if (existing.length) {
    const ids = existing.map((d) => d.id);
    await Item.deleteDocuments(ids, { pack: pack.collection });
    console.log(`Dreadlight | Cleared ${ids.length} items from ${packName}`);
  }

  // Create all items
  await Item.createDocuments(items, { pack: pack.collection });

  // Re-lock the pack
  await pack.configure({ locked: true });

  ui.notifications.info(`Dreadlight | Populated ${packName} with ${items.length} items.`);
  console.log(`Dreadlight | Populated ${packName} with ${items.length} items.`);
}

